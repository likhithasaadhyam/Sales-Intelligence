import type { Request as ExpressRequest, Response as ExpressResponse } from "express";
import { requestContext, type RequestContext } from "./lib/next-compat";

export function adaptRoute(handlerModule: any) {
  return async (req: ExpressRequest, res: ExpressResponse) => {
    try {
      const method = req.method.toUpperCase();
      const handler = handlerModule[method];

      if (!handler) {
        return res.status(405).json({ error: `Method ${method} Not Allowed` });
      }

      // Construct standard Web Request URL
      const host = req.get("host") || "localhost:5000";
      const protocol = req.protocol || "http";
      const fullUrl = `${protocol}://${host}${req.originalUrl}`;

      // Build Headers
      const headers = new Headers();
      for (const [key, val] of Object.entries(req.headers)) {
        if (Array.isArray(val)) {
          val.forEach((v) => headers.append(key, v));
        } else if (val !== undefined) {
          headers.set(key, val);
        }
      }

      // Build Request Body if applicable
      let body: any = undefined;
      if (method !== "GET" && method !== "HEAD") {
        if (req.body && typeof req.body === "object" && Object.keys(req.body).length > 0) {
          body = JSON.stringify(req.body);
          if (!headers.has("content-type")) {
            headers.set("content-type", "application/json");
          }
        } else if (typeof req.body === "string" && req.body.length > 0) {
          body = req.body;
        }
      }

      const webRequest = new Request(fullUrl, {
        method,
        headers,
        body,
      });

      // Parse incoming cookies
      const cookieMap = new Map<string, string>();
      if (req.cookies) {
        for (const [k, v] of Object.entries(req.cookies)) {
          cookieMap.set(k, String(v));
        }
      } else if (req.headers.cookie) {
        const rawCookies = req.headers.cookie.split(";");
        for (const cookieStr of rawCookies) {
          const parts = cookieStr.trim().split("=");
          if (parts.length >= 2) {
            cookieMap.set(parts[0].trim(), parts.slice(1).join("=").trim());
          }
        }
      }

      const setCookies: { name: string; value: string; options: any }[] = [];
      const ctx: RequestContext = {
        token: cookieMap.get("mentneo_session"),
        cookies: cookieMap,
        setCookies,
      };

      // Run handler inside AsyncLocalStorage context
      const response = await requestContext.run(ctx, async () => {
        return await handler(webRequest, { params: req.params });
      });

      // Process any Set-Cookie headers generated by cookies().set()
      for (const sc of setCookies) {
        res.cookie(sc.name, sc.value, sc.options);
      }

      // Send Response back to Express
      if (response instanceof Response) {
        res.status(response.status);

        response.headers.forEach((value, name) => {
          if (name.toLowerCase() !== "set-cookie") {
            res.setHeader(name, value);
          }
        });

        const contentType = response.headers.get("content-type") || "";
        if (contentType.includes("application/json")) {
          const data = await response.json();
          return res.json(data);
        } else {
          const text = await response.text();
          return res.send(text);
        }
      }

      return res.json(response);
    } catch (error: any) {
      console.error(`[API Error] ${req.method} ${req.originalUrl}:`, error);
      return res.status(500).json({ error: error.message || "Internal server error" });
    }
  };
}
